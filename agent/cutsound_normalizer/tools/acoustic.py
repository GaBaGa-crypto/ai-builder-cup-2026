# ------------------------------------------------------------------------------ loading / windows
def _resolve_window(n_total, fs, t0_s, t1_s):
    if t0_s is not None and t1_s is not None and t1_s <= t0_s:
        raise ValueError(f"t1_s ({t1_s}) <= t0_s ({t0_s})")
    dur = n_total / fs
    a = 0 if t0_s is None else int(round(min(max(float(t0_s), 0.0), dur) * fs))
    b = n_total if t1_s is None else int(round(min(max(float(t1_s), 0.0), dur) * fs))
    b = max(a, b)
    return a, b


def _load(audio, fs=None, t0_s=None, t1_s=None):
    """-> (x float64 1-D of the window, fs int, a, b) with a/b sample indices (file-local)."""
    if isinstance(audio, (str, _os.PathLike)):
        info = _sf.info(str(audio))
        fs_f = int(info.samplerate)
        a, b = _resolve_window(int(info.frames), fs_f, t0_s, t1_s)
        if b > a:
            x, _ = _sf.read(str(audio), start=a, stop=b, dtype="float64", always_2d=True)
            x = x[:, 0]
        else:
            x = _np.zeros(0)
        return _np.ascontiguousarray(x, dtype=_np.float64), fs_f, a, b
    if isinstance(audio, tuple) and len(audio) == 2 and not _np.isscalar(audio[0]):
        audio, fs = audio
    if fs is None:
        raise ValueError("fs must be given with an array input")
    arr = _np.asarray(audio)
    if arr.dtype.kind == "i":                     # GF guard (D-6): signed PCM integers -> [-1, 1) like soundfile
        arr = arr.astype(_np.float64) / float(2 ** (8 * arr.dtype.itemsize - 1))
    else:
        arr = _np.asarray(arr, dtype=_np.float64)
    if arr.ndim == 2:
        # GF guard (D-6): a (channels, samples) array (<= 8 rows, more columns) is read channel-first
        arr = arr[0] if arr.shape[0] <= 8 < arr.shape[1] else arr[:, 0]
    elif arr.ndim != 1:
        raise ValueError("audio array must be 1-D (or 2-D samples x channels)")
    fs = int(fs)
    a, b = _resolve_window(len(arr), fs, t0_s, t1_s)
    return arr[a:b], fs, a, b


_NONFINITE_MAX_FRAC = 0.5    # GF guard (D-2): more than this fraction of NaN/Inf samples -> status insufficient


def _sanitize(x):
    """GF guard (D-2): NaN/Inf samples -> 0.0.  Returns (x, n_nonfinite); all-finite input is returned as the
    same object (no copy), so finite inputs give bit-identical results."""
    if x.size == 0:
        return x, 0
    fin = _np.isfinite(x)
    if fin.all():
        return x, 0
    return _np.where(fin, x, 0.0), int(x.size - _np.count_nonzero(fin))


def _load_checked(audio, fs=None, t0_s=None, t1_s=None):
    """_load + _sanitize -> (x, fs, a, b, n_nonfinite)."""
    x, fs, a, b = _load(audio, fs, t0_s, t1_s)
    x, nbad = _sanitize(x)
    return x, fs, a, b, nbad


def _nonfinite_note(out, nbad, n):
    """Record the D-2 count in params; warning if any; returns True if the window must be 'insufficient'."""
    out["params"]["nonfinite_samples"] = int(nbad)
    if nbad:
        out["warning"] = f"{nbad} of {n} samples were NaN/Inf and were replaced by 0 before analysis"
    return bool(n) and nbad > _NONFINITE_MAX_FRAC * n


def _check_positive(name, v, allow_none=False):
    """GF guard (D-7): frame / window lengths must be finite and > 0 (else ValueError, never ZeroDivisionError)."""
    if v is None and allow_none:
        return
    if v is None or not (_np.isfinite(float(v)) and float(v) > 0):
        raise ValueError(f"{name} must be a finite number > 0 (got {v!r})")


def _validate_bands(bands, fs):
    out = []
    for lo, hi in bands:
        lo = float(lo)
        hi_eff = fs / 2.0 if hi is None else float(hi)
        if lo >= fs / 2.0 or lo >= hi_eff or (hi is not None and hi_eff > fs / 2.0 + 1e-9):
            raise ValueError(f"invalid band ({lo}, {hi}) for fs={fs}")
        out.append((lo, None if hi is None else hi_eff))
    return out


def _band_masks(f, fs, bands):
    return [(f >= lo) & ((f <= fs / 2.0) if hi is None else (f < hi)) for lo, hi in bands]


def _band_power(x, fs, bands, axis=-1):
    """Linear band energies (sum PSD * df) with the common Welch recipe; x may be 2-D (rows = frames)."""
    n = x.shape[axis]
    nper = min(4096, n)
    f, P = _welch(x, fs, window="hann", nperseg=nper, noverlap=nper // 2, detrend="constant",
                  scaling="density", axis=axis)
    df = f[1] - f[0] if len(f) > 1 else float(fs)
    return _np.stack([P[..., m].sum(axis=-1) * df for m in _band_masks(f, fs, bands)], axis=-1)


def _db(p):
    return 10.0 * _np.log10(_np.asarray(p, dtype=_np.float64) + _DB_FLOOR)


def _clip_ratio(x, level):
    return float(_np.mean(_np.abs(x) >= level)) if len(x) else 0.0


def _fl(v):
    return [float(u) for u in v]


def _common(x, fs, a, b, clip_level, clip_max):
    cr = _clip_ratio(x, clip_level)
    return {"fs": int(fs), "n_samples": int(len(x)), "duration_s": float(len(x) / fs),
            "t0_s": float(a / fs), "t1_s": float(b / fs), "clip_ratio": cr, "clipped": bool(cr > clip_max)}


def _frame_band_power(x, fs, frame_s, bands, block=512):
    """(n_frames, n_bands) linear band energies + (n_frames,) mean square on the frame grid."""
    L = int(round(frame_s * fs))
    nf = int(_np.floor(len(x) / fs / frame_s + 1e-9)) if L > 0 else 0
    nf = min(nf, len(x) // L) if L > 0 else 0
    if nf <= 0:
        return _np.zeros((0, len(bands))), _np.zeros(0), L
    fr = x[: nf * L].reshape(nf, L)
    bp = _np.empty((nf, len(bands)))
    for s in range(0, nf, block):
        bp[s: s + block] = _band_power(fr[s: s + block], fs, bands, axis=-1)
    ms = _np.mean(fr ** 2, axis=1)
    return bp, ms, L


# ------------------------------------------------------------------------------ audio_profile
def _audio_profile_impl(audio, fs, t0_s, t1_s, frame_s, bands, clip_level, clip_max):
    _check_positive("frame_s", frame_s)
    x, fs, a, b, nbad = _load_checked(audio, fs, t0_s, t1_s)
    vb = _validate_bands(bands, fs)
    out = {"method": "welch_bands_frames_v1",
           "params": {"frame_s": float(frame_s), "bands": [[float(lo), None if hi is None else float(hi)] for lo, hi in bands],
                      "clip_level": float(clip_level), "clip_max": float(clip_max),
                      "welch": "hann, nperseg=min(4096,n), 50% overlap, constant detrend, density"}}
    out.update(_common(x, fs, a, b, clip_level, clip_max))
    out["bands_hz"] = [[float(lo), float(fs / 2.0 if hi is None else hi)] for lo, hi in vb]
    t0 = a / fs
    too_bad = _nonfinite_note(out, nbad, len(x))
    if len(x) < 2 or out["duration_s"] < frame_s or too_bad:
        reason = (f"{nbad} of {len(x)} samples are NaN/Inf (> {_NONFINITE_MAX_FRAC:.0%})" if too_bad
                  else f"duration {out['duration_s']:.3f} s < frame_s {frame_s} s")
        out.update({"status": "insufficient", "reason": reason,
                    "summary": {"rms_db": float(_db(_np.mean(x ** 2)) if len(x) else -200.0),
                                "band_db": [], "clip_ratio": out["clip_ratio"],
                                "peak_abs": float(_np.max(_np.abs(x))) if len(x) else 0.0},
                    "frames": {"t_s": [], "rms_db": [], "band_db": [], "clip_ratio": []}})
        return out
    bp = _band_power(x, fs, vb)
    out["status"] = "ok"
    out["summary"] = {"rms_db": float(_db(_np.mean(x ** 2))), "band_db": _fl(_db(bp)),
                      "clip_ratio": out["clip_ratio"], "peak_abs": float(_np.max(_np.abs(x)))}
    fbp, fms, L = _frame_band_power(x, fs, frame_s, vb)
    nf = len(fms)
    fr = x[: nf * L].reshape(nf, L)
    out["frames"] = {"t_s": [float(t0 + k * frame_s) for k in range(nf)],
                     "rms_db": _fl(_db(fms)),
                     "band_db": [_fl(r) for r in _db(fbp)],
                     "clip_ratio": _fl(_np.mean(_np.abs(fr) >= clip_level, axis=1))}
    return out


# ------------------------------------------------------------------------------ change points
def _scale_points(x, fs, a, fbp, L, vb, w, min_delta_db, scale_s):
    """Change points at ONE scale (w frames = scale_s seconds before/after each frame boundary).
    Per-band dB step between the mean-power windows; local maxima of max|step| >= min_delta_db;
    persistence gate = median-of-frames step >= min_delta_db; NMS within w frames; confirmation with
    the exact common-recipe Welch band energy of the scale_s seconds before/after (the contract)."""
    nf = fbp.shape[0]
    cps = []
    if nf < 2 * w + 1:
        return cps
    E = fbp
    Edb = _db(E)
    cs = _np.vstack([_np.zeros((1, E.shape[1])), _np.cumsum(E, axis=0)])
    ks = _np.arange(w, nf - w + 1)                         # boundary k: before frames [k-w,k), after [k,k+w)
    before = (cs[ks] - cs[ks - w]) / w
    after = (cs[ks + w] - cs[ks]) / w
    D = _db(after) - _db(before)
    S = _np.max(_np.abs(D), axis=1)
    # persistence gate: median of the frame dB values (robust to short transients)
    win = _np.lib.stride_tricks.sliding_window_view(Edb, w, axis=0)   # (nf-w+1, bands, w)
    med = _np.median(win, axis=-1)                                     # med[j] = median of frames j..j+w-1
    Dm = med[ks] - med[ks - w]
    Sm = _np.max(_np.abs(Dm), axis=1)
    cand = []
    for i in range(len(ks)):
        if S[i] < min_delta_db or Sm[i] < min_delta_db:
            continue
        left = S[i - 1] if i > 0 else -_np.inf
        right = S[i + 1] if i + 1 < len(ks) else -_np.inf
        if S[i] >= left and S[i] > right:
            cand.append(i)
    cand.sort(key=lambda i: (-S[i], ks[i]))
    kept = []
    for i in cand:
        if all(abs(int(ks[i]) - int(ks[j])) > w for j in kept):
            kept.append(i)
    nw = int(round(scale_s * fs))
    for i in sorted(kept, key=lambda i: ks[i]):
        s = int(ks[i]) * L
        if s - nw < 0 or s + nw > len(x):
            continue
        bdb = _db(_band_power(x[s - nw: s], fs, vb))
        adb = _db(_band_power(x[s: s + nw], fs, vb))
        d = adb - bdb
        if _np.max(_np.abs(d)) < min_delta_db:
            continue
        rms_b = _db(_np.mean(x[s - nw: s] ** 2))
        rms_a = _db(_np.mean(x[s: s + nw] ** 2))
        dom = int(_np.argmax(_np.abs(d)))
        cps.append({"t_s": float((a + s) / fs), "scale_s": float(scale_s), "before_db": _fl(bdb), "after_db": _fl(adb),
                    "delta_db": _fl(d), "max_abs_delta_db": float(_np.max(_np.abs(d))), "dominant_band_index": dom,
                    "rms_delta_db": float(rms_a - rms_b), "score": float(S[i])})
    return cps


def _detect_change_points_impl(audio, fs, t0_s, t1_s, bands, frame_s, window_s, min_delta_db, min_duration_s,
                               clip_level, clip_max, coarse_window_s=2.0):
    _check_positive("frame_s", frame_s)
    _check_positive("window_s", window_s)
    _check_positive("coarse_window_s", coarse_window_s, allow_none=True)
    x, fs, a, b, nbad = _load_checked(audio, fs, t0_s, t1_s)
    vb = _validate_bands(bands, fs)
    w = max(1, int(round(window_s / frame_s)))
    w2 = None if coarse_window_s is None else max(1, int(round(float(coarse_window_s) / frame_s)))
    out = {"method": "frame_band_step_v2_two_scale",
           "params": {"frame_s": float(frame_s), "window_s": float(window_s), "min_delta_db": float(min_delta_db),
                      "min_duration_s": float(min_duration_s),
                      "coarse_window_s": None if coarse_window_s is None else float(coarse_window_s),
                      "bands": [[float(lo), None if hi is None else float(hi)] for lo, hi in bands],
                      "clip_level": float(clip_level), "clip_max": float(clip_max),
                      "detector": "per scale (window_s, then coarse_window_s): per-band dB step between the "
                                  "mean-power windows of w frames before/after each frame boundary; local maxima "
                                  "of max|step|; persistence gate = median-of-frames step >= min_delta_db; "
                                  "confirmation = Welch band energy of the scale before/after >= min_delta_db; "
                                  "non-maximum suppression within the scale; a coarse point is dropped if a fine "
                                  "point lies within coarse_window_s/2; coarse skipped if duration < 2*coarse_window_s",
                      "frames_per_window": w, "frames_per_coarse_window": w2}}
    out.update(_common(x, fs, a, b, clip_level, clip_max))
    out["bands_hz"] = [[float(lo), float(fs / 2.0 if hi is None else hi)] for lo, hi in vb]
    too_bad = _nonfinite_note(out, nbad, len(x))
    if out["duration_s"] < min_duration_s or too_bad:
        out.update({"status": "insufficient", "change_points": [],
                    "reason": (f"{nbad} of {len(x)} samples are NaN/Inf (> {_NONFINITE_MAX_FRAC:.0%})" if too_bad
                               else f"duration {out['duration_s']:.3f} s < min_duration_s {min_duration_s} s")})
        return out
    out["status"] = "ok"
    fbp, _, L = _frame_band_power(x, fs, frame_s, vb)
    cps = _scale_points(x, fs, a, fbp, L, vb, w, min_delta_db, float(window_s))
    coarse_ran = False
    if coarse_window_s is not None and out["duration_s"] >= 2.0 * float(coarse_window_s):
        coarse_ran = True
        half = float(coarse_window_s) / 2.0
        fine_t = [c["t_s"] for c in cps]
        for c in _scale_points(x, fs, a, fbp, L, vb, w2, min_delta_db, float(coarse_window_s)):
            if all(abs(c["t_s"] - t) > half for t in fine_t):
                cps.append(c)
    out["coarse_scale_ran"] = coarse_ran
    out["change_points"] = sorted(cps, key=lambda c: c["t_s"])
    return out


# ------------------------------------------------------------------------------ spindle speed
def _decimate(y, fs):
    if fs > _RPM_ENV_FS:
        fr = _Fraction(_RPM_ENV_FS, int(fs)).limit_denominator(1000)
        return _resample_poly(y, fr.numerator, fr.denominator), fs * fr.numerator / fr.denominator
    return y, float(fs)


def _pgram(y, fe):
    y = y - y.mean()
    n = len(y)
    nfft = _next_fast_len(_RPM_ZPAD * n)
    P = _np.abs(_rfft(y * _np.hanning(n), nfft)) ** 2
    f = _np.arange(len(P)) * fe / nfft
    m = f <= min(_RPM_FCAP_HZ * 1.05, fe / 2)
    return f[m], P[m], n / fe


def _direct_spectrum(x, fs):
    """Periodogram of the audio itself below F_CAP (rotation / tooth-pass tones radiated directly)."""
    y, fe = _decimate(x, fs)
    return _pgram(y, fe)


def _envelope_spectrum(x, fs):
    lo, hi = _RPM_CARRIER_BAND
    hi = min(hi, 0.45 * fs)
    lo = min(lo, 0.2 * hi)
    sos = _butter(4, [lo, hi], btype="band", fs=fs, output="sos")
    y = _sosfiltfilt(sos, x)
    env = _np.abs(_hilbert(y, N=_next_fast_len(len(y))))[: len(y)]
    env, fe = _decimate(env, fs)
    return _pgram(env, fe)


def _local_floor(f, P):
    """Median of P over [f/(1+r), f*(1+r)] on a log-spaced grid, interpolated in log."""
    fpos = f[f > 0]
    if len(fpos) < 8:
        return _np.full_like(P, _np.median(P) + 1e-30)
    r = 1.0 + _RPM_FLOOR_REL
    centers = _np.geomspace(max(fpos[0], 0.5), f[-1], 160)
    vals = []
    for c in centers:
        i0, i1 = _np.searchsorted(f, [c / r, c * r])
        i0 = max(0, min(i0, len(f) - 11)); i1 = max(i1, i0 + 11)
        vals.append(_np.median(P[i0:i1]))
    lv = _np.interp(_np.log(_np.maximum(f, centers[0])), _np.log(centers), _np.log(_np.asarray(vals) + 1e-30))
    return _np.exp(lv)


def _lines(f, P, T):
    """Spectral lines: local maxima with P/floor >= _RPM_LINE_SNR -> (freq refined, strength L = log10(SNR/thr))."""
    floor = _local_floor(f, P)
    snr = P / floor
    df = f[1] - f[0]
    dist = max(1, int(round((1.0 / T) / df)))
    pk, _ = _find_peaks(snr, height=_RPM_LINE_SNR, distance=dist)
    pk = pk[f[pk] > 0]
    if len(pk) == 0:
        return _np.zeros(0), _np.zeros(0)
    lp = _np.log(P + 1e-30)
    fr = []
    for i in pk:
        if 0 < i < len(P) - 1:
            y0, y1, y2 = lp[i - 1], lp[i], lp[i + 1]
            den = y0 - 2 * y1 + y2
            off = 0.5 * (y0 - y2) / den if den < 0 else 0.0
            fr.append(f[i] + max(-0.5, min(0.5, off)) * df)
        else:
            fr.append(f[i])
    return _np.asarray(fr), _np.log10(snr[pk] / _RPM_LINE_SNR)


def _harmonic_score(fr, lf, lL, T):
    """Weighted harmonic sum over slots m*fr <= F_CAP (common cap for every hypothesis).
    Returns (score, refined fr)."""
    M = max(1, int(_np.floor(_RPM_FCAP_HZ / fr)))
    m = _np.arange(1, M + 1)
    fm = m * fr
    tol = _np.maximum(2.0 / T, _RPM_HARM_TOL_REL * fm)
    idx = _np.searchsorted(lf, fm)
    best_L = _np.zeros(M); best_f = _np.zeros(M)
    for off in (-1, 0):
        j = _np.clip(idx + off, 0, len(lf) - 1)
        ok = _np.abs(lf[j] - fm) <= tol
        better = ok & (lL[j] > best_L)
        best_L = _np.where(better, lL[j], best_L)
        best_f = _np.where(better, lf[j], best_f)
    w = m ** (-_RPM_HARM_P)
    # chance level: expected slot value if the slot were placed at a random frequency
    # = P(window of width 2*tol holds a line) * mean line strength -> empty slots cost,
    # noise-only hypotheses score ~0, slots wider than the line spacing carry ~0 net evidence
    rho = len(lf) / max(_RPM_FCAP_HZ, 1.0)
    chance = _np.minimum(1.0, rho * 2.0 * tol) * (float(_np.mean(lL)) if len(lL) else 0.0)
    score = float(_np.sum(w * (best_L - chance)))
    hit = best_L > 0
    if hit.any():
        ww = best_L[hit]
        fr_ref = float(_np.sum(ww * m[hit] * best_f[hit]) / _np.sum(ww * m[hit] ** 2))
    else:
        fr_ref = float(fr)
    return score, fr_ref


_RSUB_TOP_N = 5                  # R-SUB acts on the 5 highest-scored candidates (registered)
_RSUB_MIN_PARTNER_REL = 0.5      # GT guard G2: the faster partner must carry >= 0.5 x the score of the demoted one


def _apply_rsub(cands, window, rel_tol, K, top_n=_RSUB_TOP_N):
    """R-SUB (TEST_PLAN Amendments A): among the top_n highest-scored candidates, a candidate a whose rpm is
    window[0]..window[1] x another candidate b's rpm is flagged "subsynchronous_of" (the highest-scored such
    partner) and ordered directly below every such partner.  Scores unchanged, nothing deleted.
    Two guards (GT, needed to keep the frozen v1 synthetic contract green; see progress-GT.md round 2):
      G1 same-family: the pair is skipped if a third top-n candidate c, ranked above both, has a and b as
         integer multiples (2..K within rel_tol) -- a and b are then harmonics p*c, q*c of one family
         (e.g. 3:8 = 0.375 in a 600 rpm comb), not a cage/shaft pair;
      G2 competitor: b must score >= _RSUB_MIN_PARTNER_REL x score(a) (and > 0); R-SUB resolves near-ties
         between a cage family and a shaft family, it does not let a chance-level line outrank real evidence."""
    lo, hi = float(window[0]), float(window[1])
    for c in cands:
        c["subsynchronous_of"] = None
    top = cands[:top_n]

    def _mult(x, c):
        q = x / c
        k = int(round(q))
        return 2 <= k <= K and abs(q - k) <= rel_tol * k

    partners = {}
    for i, ca in enumerate(top):
        ps = []
        for j, cb in enumerate(top):
            if j == i or cb["rpm"] <= 0 or not (lo <= ca["rpm"] / cb["rpm"] <= hi):
                continue
            if not (cb["score"] > 0 and cb["score"] >= _RSUB_MIN_PARTNER_REL * ca["score"]):
                continue                                                         # G2
            if any(_mult(ca["rpm"], top[m]["rpm"]) and _mult(cb["rpm"], top[m]["rpm"])
                   for m in range(min(i, j)) if top[m]["rpm"] > 0):
                continue                                                         # G1
            ps.append(j)
        if ps:
            partners[id(ca)] = [top[j] for j in ps]
            ca["subsynchronous_of"] = top[min(ps)]["rpm"]      # top is in score order -> highest-scored partner
    order = list(cands)
    changed = True
    while changed:                                            # terminates: partner rpm > own rpm (acyclic)
        changed = False
        for i, c in enumerate(order):
            ps = partners.get(id(c))
            if not ps:
                continue
            last = max(order.index(p_) for p_ in ps)
            if last > i:
                order.pop(i)
                order.insert(last, c)                         # directly below its lowest-placed partner
                changed = True
                break
    return order


def _estimate_spindle_speed_impl(audio, fs, t0_s, t1_s, claimed_N, Z, rpm_range, rel_tol, max_harmonic,
                                 min_duration_s, clip_level, clip_max, subsync_window=(0.35, 0.45)):
    x, fs, a, b, nbad = _load_checked(audio, fs, t0_s, t1_s)
    Zi = None if Z is None else int(Z)
    if Zi is not None and Zi < 0:                 # GF guard (D-6): a negative tooth count is invalid input
        raise ValueError(f"Z must be >= 0 (got {Z!r})")
    K = 2 * Zi if Zi else int(max_harmonic)
    # GF guard (D-1): a claim that is None, <= 0 or non-finite (spindle off / missing / corrupt) is not compared
    cn_raw = None if claimed_N is None else float(claimed_N)
    cn_ok = cn_raw is not None and bool(_np.isfinite(cn_raw)) and cn_raw > 0
    out = {"method": "envelope_direct_harmonic_sum_v3_rsub",
           "params": {"rpm_range": [float(rpm_range[0]), float(rpm_range[1])], "rel_tol": float(rel_tol),
                      "max_harmonic": int(max_harmonic), "min_duration_s": float(min_duration_s),
                      "clip_level": float(clip_level), "clip_max": float(clip_max),
                      "carrier_band_hz": list(_RPM_CARRIER_BAND), "envelope_fs": _RPM_ENV_FS,
                      "fcap_hz": _RPM_FCAP_HZ, "zero_pad": _RPM_ZPAD, "line_snr_min": _RPM_LINE_SNR,
                      "floor_rel_halfwidth": _RPM_FLOOR_REL, "harmonic_weight_p": _RPM_HARM_P,
                      "harmonic_tol_rel": _RPM_HARM_TOL_REL, "max_peaks": _RPM_MAX_PEAKS,
                      "ambiguity_K": K,
                      "subsync_window": [float(subsync_window[0]), float(subsync_window[1])], "subsync_top_n": _RSUB_TOP_N,
                      "subsync_guards": {"G1_same_family_skip": True, "G2_min_partner_score_rel": _RSUB_MIN_PARTNER_REL},
                      "line_sources": ["envelope(2-20 kHz carrier)", "direct(<= fcap)"],
                      "note": "Hilbert envelope of the 2-20 kHz band + the audio itself, each decimated to "
                              "envelope_fs, Hann periodogram; lines = local maxima >= 6x "
                              "local median floor; each line f -> rotation hypothesis 60 f and (Z given) tooth-pass "
                              "hypothesis 60 f / Z; score = sum_m m^-p [log10(SNR_m / 6)+ - chance level] over "
                              "harmonics m*f_rot <= fcap; R-SUB: among the top 5, a candidate at subsync_window x another's "
                              "rpm is flagged subsynchronous_of and ordered below it. claimed_N is only compared."}}
    out.update(_common(x, fs, a, b, clip_level, clip_max))
    out["claimed_N"] = cn_raw if cn_ok else None
    if cn_raw is not None and not cn_ok:
        out["claimed_N_ignored"] = repr(cn_raw)       # str: keeps the JSON strict for nan / inf
    out["Z"] = Zi
    too_bad = _nonfinite_note(out, nbad, len(x))
    if out["duration_s"] < min_duration_s or len(x) < 16 or too_bad:
        out.update({"status": "insufficient",
                    "reason": (f"{nbad} of {len(x)} samples are NaN/Inf (> {_NONFINITE_MAX_FRAC:.0%})" if too_bad
                               else f"duration {out['duration_s']:.3f} s < min_duration_s {min_duration_s} s"),
                    "candidates": [], "best_rpm": None, "harmonic_ambiguity": False,
                    "resolution_rpm": None,
                    "claimed_check": {"status": "insufficient", "k": None, "ratio_best_over_claimed": None,
                                      "nearest_candidate_rpm": None}})
        return out
    out["status"] = "ok"
    # line evidence = union of the lines of the envelope spectrum and of the direct spectrum (run 2)
    f, P, T = _envelope_spectrum(x, fs)
    lf_e, lL_e = _lines(f, P, T)
    f2, P2, _ = _direct_spectrum(x, fs)
    lf_d, lL_d = _lines(f2, P2, T)
    lf = _np.concatenate([lf_e, lf_d]); lL = _np.concatenate([lL_e, lL_d])
    o = _np.argsort(lf, kind="stable"); lf, lL = lf[o], lL[o]
    out["resolution_rpm"] = float(60.0 / T)
    out["n_lines"] = {"envelope": int(len(lf_e)), "direct": int(len(lf_d))}
    rmin, rmax = float(rpm_range[0]), float(rpm_range[1])
    hyps = []
    if len(lf):
        hi_f = rmax / 60.0 * (Zi if Zi else 1)
        inr = _np.flatnonzero((lf >= rmin / 60.0) & (lf <= hi_f))
        order = inr[_np.argsort(-lL[inr], kind="stable")][:_RPM_MAX_PEAKS]
        for i in order:
            fp = float(lf[i])
            opts = [(fp, "rotation")]
            if Zi:
                opts.append((fp / Zi, "tooth_pass"))
            for frh, origin in opts:
                if not (rmin <= 60.0 * frh <= rmax):
                    continue
                sc, fref = _harmonic_score(frh, lf, lL, T)
                rpm = 60.0 * fref
                if not (rmin <= rpm <= rmax):
                    rpm = 60.0 * frh
                hyps.append({"rpm": float(rpm), "f_hz": float(fp), "score": float(sc), "origin": origin})
    hyps.sort(key=lambda h: (-h["score"], h["rpm"]))
    cands = []
    for h in hyps:
        if any(abs(h["rpm"] - c["rpm"]) <= rel_tol * c["rpm"] for c in cands):
            continue
        cands.append(h)
        if len(cands) >= 10:
            break
    for c in cands:
        c["rpm"] = round(c["rpm"], 3); c["f_hz"] = round(c["f_hz"], 4); c["score"] = round(c["score"], 6)
    cands = _apply_rsub(cands, subsync_window, rel_tol, K)
    out["candidates"] = cands
    out["best_rpm"] = cands[0]["rpm"] if cands else None

    def _int_ratio(r1, r2):
        hi_, lo_ = max(r1, r2), min(r1, r2)
        if lo_ <= 0:
            return None
        q = hi_ / lo_
        k = int(round(q))
        if 2 <= k <= K and abs(q - k) <= rel_tol * k:
            return k
        return None

    top = cands[:3]
    out["harmonic_ambiguity"] = bool(any(_int_ratio(top[i]["rpm"], top[j]["rpm"]) is not None
                                         for i in range(len(top)) for j in range(i + 1, len(top))))
    if not cn_ok:
        cc = {"status": "no_claim", "k": None, "ratio_best_over_claimed": None, "nearest_candidate_rpm": None}
        if cn_raw is not None:
            cc["reason"] = f"claimed_N {cn_raw!r} is <= 0 or not finite; not compared"
    else:
        cn = cn_raw
        best = out["best_rpm"]
        near = min(cands, key=lambda c: abs(c["rpm"] - cn))["rpm"] if cands else None
        if best is None:
            cc = {"status": "mismatch", "k": None, "ratio_best_over_claimed": None, "nearest_candidate_rpm": near}
        else:
            ratio = best / cn
            if abs(best - cn) <= rel_tol * cn:
                cc = {"status": "consistent", "k": 1}
            else:
                k = _int_ratio(best, cn)
                cc = {"status": "harmonic", "k": k} if k is not None else {"status": "mismatch", "k": None}
            cc.update({"ratio_best_over_claimed": float(ratio), "nearest_candidate_rpm": near})
    out["claimed_check"] = cc
    return out


