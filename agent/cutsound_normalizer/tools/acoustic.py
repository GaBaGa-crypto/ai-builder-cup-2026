def _item_band_db(item, fs, bands, clip_level):
    if isinstance(item, dict):
        x, f_, _, _ = _load(item["path"], None, item.get("t0_s"), item.get("t1_s"))
    elif isinstance(item, tuple) and len(item) == 2:
        x, f_, _, _ = _load(item[0], item[1])
    else:
        x, f_, _, _ = _load(item, fs)
    if len(x) < 2:
        raise ValueError("empty item")
    x, nbad = _sanitize(x)                          # GF guard (D-2)
    return _db(_band_power(x, f_, _validate_bands(bands, f_))), _clip_ratio(x, clip_level), nbad, len(x)


def _auc(pos, neg):
    pos = _np.asarray(pos, dtype=_np.float64); neg = _np.asarray(neg, dtype=_np.float64)
    gt = (pos[:, None] > neg[None, :]).sum(); eq = (pos[:, None] == neg[None, :]).sum()
    return float((gt + 0.5 * eq) / (len(pos) * len(neg)))


def _cohens_d(a, b):
    """(mean(b) - mean(a)) / pooled SD (B - A, sign kept); None if < 2 per group; +-1e12 if SD ~ 0."""
    a = _np.asarray(a, dtype=_np.float64); b = _np.asarray(b, dtype=_np.float64)
    na, nb = len(a), len(b)
    if na < 2 or nb < 2:
        return None
    s = _np.sqrt(((na - 1) * a.var(ddof=1) + (nb - 1) * b.var(ddof=1)) / (na + nb - 2))
    diff = b.mean() - a.mean()
    if s < 1e-12:
        return 0.0 if diff == 0 else float(_np.sign(diff) * 1e12)
    return float(diff / s)


def _class_separability_impl(class_a, class_b, fs, bands, auc_margin, min_n, names, clip_level):
    A = [_item_band_db(it, fs, bands, clip_level) for it in class_a]
    B = [_item_band_db(it, fs, bands, clip_level) for it in class_b]
    out = {"method": "welch_band_auc_v1",
           "params": {"bands": [[float(lo), None if hi is None else float(hi)] for lo, hi in bands],
                      "auc_margin": float(auc_margin), "min_n": int(min_n), "clip_level": float(clip_level),
                      "welch": "hann, nperseg=min(4096,n), 50% overlap, constant detrend, density; one vector per item"},
           "n_a": len(A), "n_b": len(B), "names": [str(names[0]), str(names[1])],
           "bands_hz": [[float(lo), None if hi is None else float(hi)] for lo, hi in bands],
           "clip_ratio_a": [float(it[1]) for it in A], "clip_ratio_b": [float(it[1]) for it in B]}
    out["params"]["nonfinite_samples_a"] = [int(it[2]) for it in A]
    out["params"]["nonfinite_samples_b"] = [int(it[2]) for it in B]
    bad_items = sum(1 for it in A + B if it[3] and it[2] > _NONFINITE_MAX_FRAC * it[3])
    if any(it[2] for it in A + B):
        out["warning"] = (f"{sum(1 for it in A + B if it[2])} item(s) contained NaN/Inf samples (replaced by 0); "
                          f"{bad_items} item(s) are more than {_NONFINITE_MAX_FRAC:.0%} non-finite")
    per_band = []
    if A and B:
        Ea = _np.array([it[0] for it in A]); Eb = _np.array([it[0] for it in B])
        for j, (lo, hi) in enumerate(bands):
            au = _auc(Eb[:, j], Ea[:, j])
            d = abs(au - 0.5)
            per_band.append({"band_hz": [float(lo), None if hi is None else float(hi)], "auc": au, "d": d,
                             "cohens_d": _cohens_d(Ea[:, j], Eb[:, j]),
                             "mean_a_db": float(Ea[:, j].mean()), "mean_b_db": float(Eb[:, j].mean()),
                             "separable": bool(d >= auc_margin)})
    out["per_band"] = per_band
    if per_band:
        bi = int(_np.argmax([pb["d"] for pb in per_band]))
        out["best_band_index"] = bi
        out["best_auc"] = per_band[bi]["auc"]
    else:
        out["best_band_index"] = None
        out["best_auc"] = None
    if len(A) < min_n or len(B) < min_n:
        out["verdict"] = "insufficient"
        out["reason"] = f"n_a={len(A)} n_b={len(B)} < min_n={min_n}"
    elif bad_items:
        out["verdict"] = "insufficient"
        out["reason"] = f"{bad_items} item(s) are more than {_NONFINITE_MAX_FRAC:.0%} NaN/Inf samples"
    else:
        out["verdict"] = "separable" if any(pb["separable"] for pb in per_band) else "not_separable"
    return out


