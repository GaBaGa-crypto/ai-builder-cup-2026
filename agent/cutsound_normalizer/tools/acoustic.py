def _err(tool: str, e: Exception) -> Dict[str, Any]:
    return {"status": "error", "tool": tool, "error": f"{type(e).__name__}: {e}"}


# --- agent-facing guards (GF, D-3 / D-4).  None of them fires on a <= 60 s window of a >= 40 kHz file with the
# --- default frame grid, so such calls return exactly what tools_stub returns.
_AGENT_MAX_WINDOW_S = 60.0         # default analysis cap per call (s)
_AGENT_MAX_WINDOW_HARD_S = 120.0   # upper bound for max_window_s
_AGENT_MAX_FRAMES = 600            # audio_profile frames returned to the model
_AGENT_MAX_SUGGESTED = 10          # suggested windows in a window_required reply


def _agent_cap(max_window_s: Optional[float]) -> Tuple[float, bool]:
    cap = _AGENT_MAX_WINDOW_S if max_window_s is None else float(max_window_s)
    if not (_np.isfinite(cap) and cap > 0):
        raise ValueError(f"max_window_s must be a finite number > 0 (got {max_window_s!r})")
    return min(cap, _AGENT_MAX_WINDOW_HARD_S), cap > _AGENT_MAX_WINDOW_HARD_S


def _agent_window(tool: str, wav_path: str, t0_s, t1_s, max_window_s):
    """D-4: reads only the file header.  -> (window_required dict, None) or (None, fs)."""
    info = _sf.info(str(wav_path))
    fs = int(info.samplerate)
    dur = float(info.frames) / fs
    cap, clamped = _agent_cap(max_window_s)
    a = 0.0 if t0_s is None else min(max(float(t0_s), 0.0), dur)
    b = dur if t1_s is None else min(max(float(t1_s), 0.0), dur)
    span = b - a
    if span <= cap + 1e-9:                     # also t1 <= t0: the core raises the contract ValueError
        return None, fs
    n = min(_AGENT_MAX_SUGGESTED, int(_np.ceil(span / cap - 1e-9)))
    starts = _np.linspace(a, b - cap, n) if n > 1 else _np.array([a])
    wins = [[round(float(s), 3), round(float(s) + cap, 3)] for s in starts]
    return {"status": "window_required", "tool": tool,
            "reason": f"requested window {span:.1f} s exceeds max_window_s {cap:g} s; the whole span is not analysed",
            "fs": fs, "file_duration_s": dur, "requested_t0_s": a, "requested_t1_s": b,
            "max_window_s": cap, "max_window_s_hard_limit": _AGENT_MAX_WINDOW_HARD_S,
            "max_window_s_clamped": bool(clamped),
            "suggested_windows": wins, "suggested_coverage_fraction": round(min(1.0, n * cap / span), 4),
            "hint": "call again with t0_s/t1_s of one suggested window (or any window <= max_window_s); "
                    "use several calls to cover more of the file"}, None


def _agent_bands(fs: int):
    """D-3: the DEFAULT_BANDS that lie wholly below Nyquist -> (bands, original indices)."""
    idx = [i for i, (lo, hi) in enumerate(DEFAULT_BANDS) if hi <= fs / 2.0 + 1e-9]
    if not idx:
        raise ValueError(f"fs={fs} Hz: no default band lies below Nyquist ({fs / 2.0:g} Hz)")
    return tuple(DEFAULT_BANDS[i] for i in idx), idx


def _expand(vals, idx):
    full = [None] * len(DEFAULT_BANDS)
    for k, i in enumerate(idx):
        full[i] = vals[k]
    return full


def _mark_bandlimited(res: Dict[str, Any], idx, fs: int) -> None:
    res["params"]["bandlimited"] = True
    res["params"]["nyquist_hz"] = fs / 2.0
    res["params"]["bands_unavailable_hz"] = [[lo, hi] for i, (lo, hi) in enumerate(DEFAULT_BANDS) if i not in idx]
    res["bands_hz"] = [[lo, hi] for lo, hi in DEFAULT_BANDS]


def _pmean_db(rows) -> List[float]:
    """Power average of dB values along axis 0 (frames of one group)."""
    p = _np.power(10.0, _np.asarray(rows, dtype=_np.float64) / 10.0)
    return _fl(_db(p.mean(axis=0)))


def _cap_frames(res: Dict[str, Any], max_frames: int = _AGENT_MAX_FRAMES) -> None:
    """D-4: at most max_frames frames go back to the model; longer grids are power-averaged in groups of g."""
    fr = res.get("frames") or {}
    nf = len(fr.get("t_s", []))
    if nf <= max_frames:
        return
    g = int(_np.ceil(nf / max_frames))
    starts = list(range(0, nf, g))
    res["frames"] = {"t_s": [fr["t_s"][s] for s in starts],
                     "rms_db": [_pmean_db([[v] for v in fr["rms_db"][s: s + g]])[0] for s in starts],
                     "band_db": [_pmean_db(fr["band_db"][s: s + g]) for s in starts],
                     "clip_ratio": [float(_np.mean(fr["clip_ratio"][s: s + g])) for s in starts],
                     "n_frames_in_group": [min(g, nf - s) for s in starts]}
    res["frames_downsampled_by"] = g
    res["n_frames_original"] = nf
    res["params"]["frames_downsampled_by"] = g
    res["params"]["frame_s_returned"] = float(res["params"]["frame_s"]) * g


def audio_profile(wav_path: str, t0_s: Optional[float] = None, t1_s: Optional[float] = None,
                  frame_s: float = 0.1, max_window_s: float = 60.0) -> dict:
    """Band-energy / RMS / clipping profile of one WAV file window (at most max_window_s seconds per call).

    Args:
        wav_path: Path to a WAV file (multi-channel files are reduced to channel 0).
        t0_s: Window start in file-local seconds (None = file start).
        t1_s: Window end in file-local seconds (None = file end).
        frame_s: Frame length of the time grid in seconds (default 0.1, the viewer grid).
        max_window_s: Longest window analysed in one call (default 60, at most 120).  A longer request
            (including a whole long file when t0_s/t1_s are omitted) returns status "window_required" with
            file_duration_s and suggested_windows, and nothing is analysed.

    Returns:
        dict with status (ok | insufficient | window_required | error), summary (rms_db, band_db for
        0-2k/2-4k/4-8k/8-12k/12-16k/16-20k Hz, clip_ratio, peak_abs), frames (t_s file-local frame start
        times, rms_db, band_db, clip_ratio; at most 600 frames, longer grids are power-averaged and
        frames_downsampled_by says by how much), clip_ratio, clipped (clip_ratio > 1 %), method and params.
        For files sampled below 40 kHz the bands above Nyquist are null and params.bandlimited is true.
    """
    try:
        req, fs = _agent_window("audio_profile", wav_path, t0_s, t1_s, max_window_s)
        if req:
            return req
        bands, idx = _agent_bands(fs)
        res = _audio_profile_impl(wav_path, None, t0_s, t1_s, float(frame_s), bands, 0.999, 0.01)
        _cap_frames(res)
        if len(idx) < len(DEFAULT_BANDS):
            _mark_bandlimited(res, idx, fs)
            if res["summary"].get("band_db"):
                res["summary"]["band_db"] = _expand(res["summary"]["band_db"], idx)
            res["frames"]["band_db"] = [_expand(r, idx) for r in res["frames"]["band_db"]]
        return res
    except Exception as e:  # noqa: BLE001
        return _err("audio_profile", e)


def detect_change_points(wav_path: str, t0_s: Optional[float] = None, t1_s: Optional[float] = None,
                         min_delta_db: float = 6.0, window_s: float = 0.5,
                         coarse_window_s: Optional[float] = 2.0, max_window_s: float = 60.0) -> dict:
    """Find times where the band energy changes persistently (a step or a slow ramp, not a transient).

    A point is reported only if, in at least one band, the energy of the window_s seconds after it differs
    from the window_s seconds before it by >= min_delta_db.  A second, coarse scale (coarse_window_s windows)
    also reports ramps that reach min_delta_db only over ~2 s, at the ramp midpoint (located to
    +- coarse_window_s / 2); a fine point within coarse_window_s / 2 wins.  Inputs shorter than 2 s return
    status "insufficient" with an empty list.  Points closer than coarse_window_s to a window edge cannot be
    found, so overlap consecutive windows by a few seconds.

    Args:
        wav_path: Path to a WAV file.
        t0_s: Window start in file-local seconds (None = file start).
        t1_s: Window end in file-local seconds (None = file end).
        min_delta_db: Minimum band-energy step in dB (default 6).
        window_s: Length of the before/after comparison windows in seconds (default 0.5).
        coarse_window_s: Coarse-scale window in seconds for ramps (default 2.0; None disables it; skipped
            when the input is shorter than twice this value).
        max_window_s: Longest window analysed in one call (default 60, at most 120); a longer request returns
            status "window_required" with suggested_windows and nothing is analysed.

    Returns:
        dict with status, change_points (t_s file-local, scale_s, before_db, after_db, delta_db per band,
        max_abs_delta_db, dominant_band_index, rms_delta_db, score), bands_hz, clip_ratio, clipped,
        method and params.  Below 40 kHz sampling, per-band values above Nyquist are null (params.bandlimited).
    """
    try:
        req, fs = _agent_window("detect_change_points", wav_path, t0_s, t1_s, max_window_s)
        if req:
            return req
        bands, idx = _agent_bands(fs)
        res = _detect_change_points_impl(wav_path, None, t0_s, t1_s, bands, 0.1, float(window_s),
                                         float(min_delta_db), 2.0, 0.999, 0.01,
                                         None if coarse_window_s is None else float(coarse_window_s))
        if len(idx) < len(DEFAULT_BANDS):
            _mark_bandlimited(res, idx, fs)
            for c in res.get("change_points", []):
                for k in ("before_db", "after_db", "delta_db"):
                    c[k] = _expand(c[k], idx)
                c["dominant_band_index"] = idx[c["dominant_band_index"]]
        return res
    except Exception as e:  # noqa: BLE001
        return _err("detect_change_points", e)


def estimate_spindle_speed(wav_path: str, t0_s: Optional[float] = None, t1_s: Optional[float] = None,
                           claimed_rpm: Optional[float] = None, flutes: Optional[int] = None,
                           max_window_s: float = 60.0) -> dict:
    """Spindle-speed hypotheses from rotation-locked spectral lines, compared with a claimed speed.

    The claimed speed is only compared, never used to steer the estimate; a claim <= 0 or not finite
    (e.g. spindle off) is treated as no claim.  With flutes (number of teeth Z) a line at f Hz is also
    offered as tooth-pass (rpm = 60 f / Z).  A candidate at 0.35-0.45 x another top-5 candidate's rpm
    (bearing-cage-like, sub-synchronous) is flagged subsynchronous_of and ranked below it (never deleted).
    Inputs shorter than 2 s return status "insufficient".  status "ok" does NOT mean a periodicity was
    found: read the candidates' score (chance level is about 0; pure white noise gave a top score of 0.35
    in a probe, real spindle families score several units) before trusting best_rpm.

    Args:
        wav_path: Path to a WAV file.
        t0_s: Window start in file-local seconds (None = file start).
        t1_s: Window end in file-local seconds (None = file end).
        claimed_rpm: Spindle speed stated by the metadata / label, if any.
        flutes: Number of cutter teeth Z, if known.
        max_window_s: Longest window analysed in one call (default 60, at most 120); a longer request returns
            status "window_required" with suggested_windows and nothing is analysed.  Prefer one cutting
            pass (one constant spindle speed) per call.

    Returns:
        dict with status, candidates (rpm, f_hz, score, origin, subsynchronous_of; best first, <= 10), best_rpm,
        harmonic_ambiguity (two of the top-3 candidates at an integer ratio -> ask, do not conclude),
        resolution_rpm, claimed_check (status no_claim | consistent | harmonic | mismatch | insufficient, k,
        ratio_best_over_claimed, nearest_candidate_rpm), clip_ratio, clipped, method and params.
    """
    try:
        req, _fs = _agent_window("estimate_spindle_speed", wav_path, t0_s, t1_s, max_window_s)
        if req:
            return req
        return _estimate_spindle_speed_impl(wav_path, None, t0_s, t1_s, claimed_rpm,
                                            None if flutes is None else int(flutes), (100.0, 30000.0), 0.03, 8,
                                            2.0, 0.999, 0.01, (0.35, 0.45))
    except Exception as e:  # noqa: BLE001
        return _err("estimate_spindle_speed", e)


def class_separability(paths_a: List[str], paths_b: List[str], name_a: str = "A", name_b: str = "B",
                       max_seconds: Optional[float] = None) -> dict:
    """Per-band separability of two classes of recordings (one Welch band-energy vector per file).

    Args:
        paths_a: WAV paths of class A.
        paths_b: WAV paths of class B.
        name_a: Display name of class A.
        name_b: Display name of class B.
        max_seconds: Analyse at most the first max_seconds of each file (None = 60; at most 120).  Files
            longer than that are truncated and counted in params.items_truncated.

    Returns:
        dict with verdict (separable | not_separable | insufficient when a class has < 3 files), per_band
        (band_hz, auc = P(B > A), d = |auc - 0.5|, cohens_d (B - A), mean_a_db, mean_b_db, separable iff
        d >= 0.25), best_band_index, best_auc, n_a, n_b, clip_ratio_a / clip_ratio_b per file, method, params.
        If any file is sampled below 40 kHz, bands above the lowest Nyquist are null (params.bandlimited).
    """
    try:
        cap, _clamped = _agent_cap(max_seconds)
        infos = [_sf.info(str(p)) for p in list(paths_a) + list(paths_b)]
        fs_min = min(int(i.samplerate) for i in infos) if infos else 48000
        n_trunc = sum(1 for i in infos if float(i.frames) / int(i.samplerate) > cap + 1e-9)
        tcap = cap if (n_trunc or max_seconds is not None) else None
        bands, idx = _agent_bands(fs_min)
        A = [{"path": p, "t0_s": None, "t1_s": tcap} for p in paths_a]
        B = [{"path": p, "t0_s": None, "t1_s": tcap} for p in paths_b]
        res = _class_separability_impl(A, B, None, bands, 0.25, 3, (str(name_a), str(name_b)), 0.999)
        if n_trunc:
            res["params"]["max_seconds_per_item"] = cap
            res["params"]["items_truncated"] = n_trunc
        if len(idx) < len(DEFAULT_BANDS):
            _mark_bandlimited(res, idx, fs_min)
            pb = res["per_band"]
            res["per_band"] = [pb[idx.index(j)] if j in idx else
                               {"band_hz": [lo, hi], "auc": None, "d": None, "cohens_d": None, "mean_a_db": None,
                                "mean_b_db": None, "separable": None}
                               for j, (lo, hi) in enumerate(DEFAULT_BANDS)] if pb else pb
            if res.get("best_band_index") is not None:
                res["best_band_index"] = idx[res["best_band_index"]]
        return res
    except Exception as e:  # noqa: BLE001
        return _err("class_separability", e)
